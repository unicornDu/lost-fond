import { ref } from 'vue'

/**
 * 轻量 i18n（不引第三方依赖）。
 *
 * 设计：
 * - `locale` 是全局 ref，`t()` 在渲染期读取它 → 切语言后用到 $t 的模板自动重渲染；
 * - 模板里直接用 `$t('nav.home')`（main.js 注入 globalProperties），
 *   脚本里 `import { t, locale } from '../i18n'`；
 * - 词条 key 采用扁平命名：nav.* / status.* / cat.* / home.* / wall.* / detail.* …
 * - **只翻译界面文案**：启事标题/描述/地点等用户生成内容保持原样，分类与状态做显示层映射。
 * - 后台（/admin）与公开首页保持中文：前者是内部工具，后者是中文编辑排版的品牌页。
 */

export const LOCALES = [
  { code: 'zh-CN', short: '简', label: '简体中文' },
  { code: 'zh-TW', short: '繁', label: '繁體中文' },
  { code: 'en', short: 'EN', label: 'English' },
]

const KEY = 'shiguang_locale'

function readLocale() {
  try {
    const v = localStorage.getItem(KEY)
    if (v && LOCALES.some((l) => l.code === v)) return v
  } catch (e) { /* 隐私模式忽略 */ }
  return 'zh-CN'
}

export const locale = ref(readLocale())

export function setLocale(code) {
  const next = LOCALES.some((l) => l.code === code) ? code : 'zh-CN'
  locale.value = next
  try { localStorage.setItem(KEY, next) } catch (e) { /* 隐私模式忽略 */ }
  document.documentElement.lang = next === 'en' ? 'en' : next
}

export function t(key, params) {
  const table = DICT[locale.value] || DICT['zh-CN']
  let s = table[key] ?? DICT['zh-CN'][key] ?? key
  if (params) {
    for (const k of Object.keys(params)) s = s.split(`{${k}}`).join(String(params[k]))
  }
  return s
}

